use serde::{Deserialize, Serialize};

/// Area Root Server identifier.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum AreaServer {
    Delta = 0,
    Theta = 1,
    Lambda = 2,
    Sigma = 3,
    Omega = 4,
}

impl AreaServer {
    pub const fn name(&self) -> &'static str {
        match self {
            Self::Delta => "Delta",
            Self::Theta => "Theta",
            Self::Lambda => "Lambda",
            Self::Sigma => "Sigma",
            Self::Omega => "Omega",
        }
    }

    pub const fn mark(&self) -> &'static str {
        match self {
            Self::Delta => "\u{0394}",
            Self::Theta => "\u{0398}",
            Self::Lambda => "\u{039B}",
            Self::Sigma => "\u{03A3}",
            Self::Omega => "\u{03A9}",
        }
    }
}

/// Slot position for an Area Word.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum AreaWordSlot {
    First = 0,
    Second = 1,
    Third = 2,
}

impl AreaWordSlot {
    pub const fn index(&self) -> usize {
        *self as usize
    }

    pub const fn label(&self) -> &'static str {
        match self {
            Self::First => "1st",
            Self::Second => "2nd",
            Self::Third => "3rd",
        }
    }
}

