/// 32-bit Mersenne Twister MT19937 PRNG from `hackGU_vol1.dll`.
#[derive(Clone, Debug)]
pub struct Mt19937 {
    mt: [u32; 624],
    mti: usize,
}

impl Mt19937 {
    pub fn new(seed: u32) -> Self {
        let mut rng = Self {
            mt: [0; 624],
            mti: 624,
        };
        rng.seed(seed);
        rng
    }

    pub fn seed(&mut self, s: u32) {
        self.mt[0] = s;
        for i in 1..624 {
            let prev = self.mt[i - 1];
            self.mt[i] = (0x6C078965_u32.wrapping_mul(prev ^ (prev >> 30))).wrapping_add(i as u32);
        }
        self.mti = 624;
    }

    pub fn rand(&mut self) -> u32 {
        if self.mti >= 624 {
            const MAG01: [u32; 2] = [0, 0x9908B0DF];
            for kk in 0..(624 - 397) {
                let y = (self.mt[kk] & 0x80000000) | (self.mt[kk + 1] & 0x7FFFFFFF);
                self.mt[kk] = self.mt[kk + 397] ^ (y >> 1) ^ MAG01[(y & 1) as usize];
            }
            for kk in (624 - 397)..623 {
                let y = (self.mt[kk] & 0x80000000) | (self.mt[kk + 1] & 0x7FFFFFFF);
                self.mt[kk] = self.mt[kk + 397 - 624] ^ (y >> 1) ^ MAG01[(y & 1) as usize];
            }
            let y = (self.mt[623] & 0x80000000) | (self.mt[0] & 0x7FFFFFFF);
            self.mt[623] = self.mt[396] ^ (y >> 1) ^ MAG01[(y & 1) as usize];
            self.mti = 0;
        }

        let mut y = self.mt[self.mti];
        self.mti += 1;

        y ^= y >> 11;
        y ^= (y << 7) & 0x9D2C5680;
        y ^= (y << 15) & 0xEFC60000;
        y ^= y >> 18;
        y
    }
}

