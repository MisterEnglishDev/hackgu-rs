pub const MSG_MISSION_BOSS: u32 = 0x4E98AA45;
pub const MSG_MISSION_TEMPLE: u32 = 0x457C319B;

pub fn words_for_slot(slot: AreaWordSlot) -> &'static [WordAttribute] {
    match slot {
        AreaWordSlot::First => &WORDS_SLOT1,
        AreaWordSlot::Second => &WORDS_SLOT2,
        AreaWordSlot::Third => &WORDS_SLOT3,
    }
}

pub fn get_word(slot: AreaWordSlot, index: usize) -> Option<&'static WordAttribute> {
    words_for_slot(slot).get(index)
}

pub fn get_word_by_msg_id(msg_id: u32) -> Option<&'static WordAttribute> {
    for slot in [AreaWordSlot::First, AreaWordSlot::Second, AreaWordSlot::Third] {
        if let Some(w) = words_for_slot(slot).iter().find(|w| w.msg_id == msg_id) {
            return Some(w);
        }
    }
    None
}

pub fn get_word_by_word_id(slot: AreaWordSlot, word_id: u16) -> Option<&'static WordAttribute> {
    words_for_slot(slot).iter().find(|w| w.word_id == word_id)
}

pub fn total_words(slot: AreaWordSlot) -> usize {
    words_for_slot(slot).len()
}

pub fn initial_owned_words(slot: AreaWordSlot) -> Vec<usize> {
    words_for_slot(slot)
        .iter()
        .enumerate()
        .filter_map(|(idx, w)| if w.available_at_start { Some(idx) } else { None })
        .collect()
}

/// Help-line monster difficulty text key based on `Area LV min - Haseo LV`.
pub const fn help_monster_msg(area_lv_min: i32, haseo_lv: i32) -> u32 {
    let diff = area_lv_min - haseo_lv;
    if diff >= 5 {
        0xA097AECB
    } else if diff >= 3 {
        0xADD48812
    } else if diff >= 1 {
        0xA91595A5
    } else if diff == 0 {
        0xB752C5A0
    } else if diff >= -2 {
        0xB393D817
    } else if diff >= -4 {
        0xBED0FECE
    } else {
        0xBA11E379
    }
}

/// Help-line item quality text key based on `Area LV max - Haseo LV`.
pub const fn help_item_msg(area_lv_max: i32, haseo_lv: i32) -> u32 {
    let diff = area_lv_max - haseo_lv;
    if diff >= 5 {
        0x52A0FDF4
    } else if diff >= 3 {
        0x5FE3DB2D
    } else if diff >= 1 {
        0x5B22C69A
    } else if diff == 0 {
        0x4565969F
    } else if diff >= -2 {
        0x41A48B28
    } else if diff >= -4 {
        0x4CE7ADF1
    } else {
        0x4826B046
    }
}

/// Synthesize an Area from the given Root Server and words.
/// Matches `hackGU_vol1.dll` functions `sub_2848F0`, `sub_67C8B0`, and `sub_67C410`.
pub fn synthesize_area(
    server: AreaServer,
    w1: Option<&WordAttribute>,
    w2: Option<&WordAttribute>,
    w3: Option<&WordAttribute>,
    haseo_lv: u32,
) -> SynthesizedArea {
    // 1. Mersenne Twister PRNG seed formula (sub_67C8B0 RVA 0x0067C92D..0x0067C998)
    let mut seed: u32 = 0;
    if let Some(w1) = w1 {
        seed = (((server as u32 & 0xFF) << 8) | (w1.word_id as u32 & 0xFFFF)) << 16;
    }
    if let Some(w2) = w2 {
        seed |= (w2.word_id as u32 & 0xFFFF) << 8;
    }
    if let Some(w3) = w3 {
        seed |= w3.word_id as u32 & 0xFFFF;
    }
    let mut rng = Mt19937::new(seed);

    // 2. Base Area Level & Clamping (sub_67C8B0 RVA 0x0067CA50..0x0067CB08)
    let base_bracket = w1.map(|w| w.level_contribution).unwrap_or(1);
    let mut base_lv = (base_bracket * 10) - 9;
    if let Some(w2) = w2 {
        if w2.level_contribution != -1 {
            base_lv += w2.level_contribution;
        }
    }

    let mut area_lv_min = base_lv;
    let mut area_lv_max = base_lv;
    if let Some(w3) = w3 {
        if w3.min_lv_offset != -1 {
            area_lv_min += w3.min_lv_offset;
        }
        if w3.max_lv_offset != -1 {
            area_lv_max += w3.max_lv_offset;
        }
    }
    let area_lv_min = area_lv_min.clamp(1, 50) as u32;
    let area_lv_max = area_lv_max.clamp(1, 50) as u32;
    let area_lv = area_lv_min;
    let treasure_lv = area_lv_max;

    // 3. Elements bitfield (sub_2848F0 RVA 0x00284A09..0x00284A3C)
    let mut elements = [false; 6];
    for w in [w1, w2, w3].into_iter().flatten() {
        if w.element >= 0 && w.element < 6 {
            elements[w.element as usize] = true;
        }
    }

    // 4. Special/Story Area lookup (sub_67C8B0 RVA 0x0067CB45..0x0067CB90)
    let special_match = match (w1, w2, w3) {
        (Some(w1), Some(w2), Some(w3)) => {
            SPECIAL_AREAS.iter().find(|entry| {
                entry.server == server
                    && entry.w1_idx == w1.index
                    && entry.w2_idx == w2.index
                    && entry.w3_idx == w3.index
            })
        }
        _ => None,
    };

    // 5. Environment, Stage Kit, and Thumbnail Cell (TEX_xsrnd_01)
    let (env_type, stage_idx, thumbnail_cell, is_special, special_id, party_count, player_count) =
        if let Some(special) = special_match {
            let env_type = special.env_type;
            let tilekit = special.tilekit_index;
            let stage_idx = match env_type {
                0 => 2 + tilekit,
                2 => 0,
                3 => 1,
                // Type 4 (Lost Ground) stage/thumbnail mapping is an assumption (xse1_* cells not traced).
                4 => 7 + tilekit,
                _ => 2 + tilekit,
            };
            // Special area bypasses encounter population (sub_67C410 jump at 0x0067C71F)
            (env_type, stage_idx, stage_idx, true, Some(special.special_id), 0, 0)
        } else {
            let env_type = w1.map(|w| w.env_type).unwrap_or(0);
            let tilekit = if env_type == 0 {
                (rng.rand() % 5) as usize
            } else {
                0
            };
            let stage_idx = match env_type {
                0 => 2 + tilekit,
                2 => 0,
                3 => 1,
                _ => 2 + tilekit,
            };
            // PLACEHOLDER (not traced): the original runs its wanderer generator (sub_67C080) here; "002" is only the
            // value seen in the reference capture for Δ Courageous alone, so it is reproduced as a constant.
            let parties = if w1.is_some() { 2 } else { 0 };
            (env_type, stage_idx, stage_idx, false, None, parties, 0)
        };

    // 6. Treasure gauge balance (sub_2848F0 RVA 0x00284C3D..0x00284C8C)
    let treasure_gauge = w3
        .map(|w| if w.max_lv_offset != -1 { w.max_lv_offset } else { 0 })
        .unwrap_or(0)
        .clamp(-3, 3);

    // 7. Mission ID determination (sub_67C8B0 RVA 0x0067CBD4..0x0067CC25)
    let mission_id = if let Some(w2) = w2 {
        match w2.mission_override {
            2 => MSG_MISSION_TEMPLE,
            3 => 0,
            _ => MSG_MISSION_BOSS,
        }
    } else {
        MSG_MISSION_BOSS
    };

    // 8. Help-line status messages (sub_27DD10 RVA 0x0027DD10..0x0027DFDC)
    let monster_help_msg_id = if env_type == 4 {
        0x3764FC21 // Lost Ground help
    } else {
        help_monster_msg(area_lv_min as i32, haseo_lv as i32)
    };
    let item_help_msg_id = help_item_msg(area_lv_max as i32, haseo_lv as i32);

    SynthesizedArea {
        server,
        area_lv,
        area_lv_min,
        area_lv_max,
        elements,
        env_type,
        stage_idx,
        thumbnail_cell,
        mission_id,
        party_count,
        player_count,
        treasure_lv,
        treasure_gauge,
        monster_help_msg_id,
        item_help_msg_id,
        is_special,
        special_id,
    }
}

